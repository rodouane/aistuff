    fun normalize(s: String): String =
        Normalizer.normalize(s.uppercase(), Normalizer.Form.NFD).replace(Regex("\\p{Mn}+"), "")

    fun glyph(c: Char): Array<String> = glyphs[c] ?: glyphs.getValue(' ')

    fun width(s: String, scale: Int = 1): Int {
